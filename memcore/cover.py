"""他一条说了几件事：只用来说数，不给他列清单（2026-11-06）。

**为什么只给数、不给内容**：人设那条「不用演」的意思是，一旦给了例子她就会照着念。
所以这里**不把三件事的标题写进注入**（那会变成让她念清单），只告诉她
"这一条里有几件，不是一句"，接不接、怎么接由她自己定。

**为什么要有**：实测 157 组成对消息 —— 他短句（13 字）她回 53 字；
他长段（175 字）她只回 102 字，而且只接其中一件。他自己在记忆里就提过
（「希望助手对她发的一长串内容逐条回应，而不是只挑一条接」）。
人机感的主要来源不是用词，是**话没被接住**。

**只影响这一次**：跟 `style.py` 同一类 —— 这一轮他的话确实长才出现，
他的话短就一个字都不加。不写进人设、不改性格。
"""
from __future__ import annotations

import re

# 2026-11-08 晚（他的口径）：**不设字数门槛**。
# "不管字数多少，都应该能够多点回答。"
# 原来 80→40 那条线是按他的输入长度拍的（中位 18 字、p75 42 字），
# 结果短消息一律不提 —— 可短句里照样能塞三件事：
#   "锅底不平。面煮糊了。我妈在旁边看着。"
# 现在只看**能切出几件**，不看总长度。切不出两件就不提，切得出就提。
MAX_ITEMS = 4
# 短于这个字数的不算一件事。2026-11-08：5 → 3 → **2**。
# 5 字会把"锅底不平"整句吃掉；3 字还会把"累了。早点睡。"里的"累了"吃掉，
# 明明两件事只剩一件。2 是下限：再低就是单字噪声了。
MIN_ITEM = 2

_SPLIT = re.compile(r"[。！？!?；;\n]+")
# 纯连接词/应答词不算一件事（"好。""嗯。""对。"这种不是他在说事）
_FILLER = re.compile(
    r"^(那个|然后|对了|就是|其实|不过|而且|还有|嗯|哎|哦|所以|反正|话说|"
    r"我说|你说|但是|因为|另外|还有一点|"
    r"好|行|对|是|不|没|在|成|可以|收到|懂了|知道了|好的|是啊|对啊|"
    r"好吧|行吧|那行|嗯嗯|好嘞|哈哈|真的|确实)$"
)


def items(text: str) -> list[str]:
    """把他的话粗切成"几件"。只用来数数，内容不注入。

    Args:
        text: 他那条原话。

    Returns:
        每一件的片段（已去空白、去纯连接词），按原顺序。
    """
    out: list[str] = []
    for piece in _SPLIT.split(text or ""):
        s = piece.strip()
        if len(s) < MIN_ITEM:
            continue
        if _FILLER.match(s):
            continue
        out.append(s)
    return out


def count(text: str) -> int:
    """他这条里大概有几件事（上限 MAX_ITEMS）。"""
    return min(len(items(text)), MAX_ITEMS)


def should(text: str) -> bool:
    """这一轮该不该提这件事。

    判据只有一条：**切得出两件以上**。不看字数、不看问号个数。
    短句里一件事就是一件事，不该因为整条短就当没听见。
    """
    return count(text or "") >= 2


def line(text: str) -> str:
    """拼在【这次】那一行后面的半句。空字符串表示这一轮不加。

    措辞用「可以」——是许可不是命令；也不点名是哪几件（点了她就开始念）。
    """
    if not (text or "").strip() or not should(text):
        return ""
    n = count(text)
    if n <= 1:
        return ""
    return f"他这一条里有{n}件不同的事，不是一句；可以挨个应，不用合成一段。"
