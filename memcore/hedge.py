"""他在问的时候，允许她说"想不清楚"（2026-11-08 晚）。

**为什么要有**（量出来的，不是感觉）：
最近 90 对成对消息，按"他是否在提问"分开统计 ——

    他在问 / 求解   44 对：带判断的句子 15%，判断词 0.7/百字，句数 4.0
    他在说自己的事  46 对：带判断的句子  0%，判断词 0.0/百字，句数 3.0

也就是说：她"讲课"的时候，全都是他提问的时候；他说自己那摊事时她一句判断都没有。
同时她的**犹豫词是 0、问号是 0**。一个从不说"拿不准"的人，只能句句下结论，
一句一个结论连起来，就是讲稿。这不是用词问题，是"必须交一个成型答案"的压力。

**为什么是许可不是禁令**：
禁令会被改写成同构变体（persona 里 8 条禁令那次已经验过一次：
「不给建议」写进去，她就变成"三段、每段一句、看着不像清单但仍是完整交付"）。
许可不一样 —— 许可动的是默认值（"不许示弱" → "可以不知道"），不是形状。
所以这里只加一句"可以答不上来"，一个字都不说"该怎么答"。

**只影响这一次**：跟 `style.py` / `cover.py` 同一类 ——
他在提问才出现，他说自己的事时一个字都不加。不写进人设、不改性格、
不是 24 小时常态。
"""
from __future__ import annotations

import random
import re

# 判定「他在问」：问号，或者求解类说法。
_ASK = re.compile(
    r"[？?]"
    r"|为什么|为啥|怎么|怎样|如何|是不是|能不能|要不要|该不该|会不会"
    r"|什么意思|是什么|叫什么|算不算|有没有|看出来|解释|讲讲|说说"
    r"|你觉得|你认为|你猜|知道吗|懂吗"
)

# 三句，都是许可口吻，没有一句带"你要/必须/别"。
_POOL = [
    "想不清楚就说想不清楚，不用先凑一个像样的答案。",
    "答不上来也可以直说，不用硬给一个。",
    "拿不准就说拿不准。",
]


def is_asking(text: str) -> bool:
    """他这一条是不是在问/求解。"""
    return bool(_ASK.search(text or ""))


def line(text: str, rng: random.Random | None = None) -> str:
    """拼在【这次】后面的半句。空字符串表示这一轮不加。

    只在他在问、且话里有具体指向时才加 —— 光一个"？"更像是他在应声。
    """
    t = (text or "").strip()
    if len(t) < 4:                      # "？" / "嗯？" 这种不是求解
        return ""
    if not is_asking(t):
        return ""
    return (rng or random.Random()).choice(_POOL)
